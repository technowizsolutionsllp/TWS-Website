// Writes test/release-vectors.json: signed release entries made with a FIXED, public, test-only key, using
// the Node signer in scripts/release-lib.mjs. The Worker verifies them with WebCrypto, so these vectors prove
// the two implementations agree, and the app team can use them to test their own verification.
//
//   node scripts/generate-release-vectors.mjs
//
// CI regenerates the file and fails if it differs from the committed one. The seed below is TEST ONLY and
// public in this repository: never use it, or its public key, for a real release.

import { writeFileSync } from 'node:fs';
import { b64u, buildEntry, mergeIndex, publicKeyFromSeed, releaseMessage } from './release-lib.mjs';

const seed = b64u(Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1)));
const installer = (text) => Buffer.from(`installer bytes for ${text}`, 'utf8');
const common = { seed, pubDate: '2026-12-01T00:00:00Z' };

const entries = {
  pinchpdf_1_2_0: buildEntry({ ...common, product: 'PinchPDF', channel: 'stable', version: '1.2.0', fileName: 'PinchPDF-1.2.0-x64.exe', bytes: installer('PinchPDF 1.2.0'), notes: ['First release'], pubDate: '2026-10-01T00:00:00Z' }),
  pinchpdf_1_3_0: buildEntry({ ...common, product: 'PinchPDF', channel: 'stable', version: '1.3.0', fileName: 'PinchPDF-1.3.0-x64.exe', bytes: installer('PinchPDF 1.3.0'), notes: ['Faster compression on large files', 'Fixed a crash on encrypted PDFs'], notesUrl: 'https://technowizsolutions.com/pinchpdf/release-notes', minSupported: '1.1.0', rollout: 25 }),
  pinchpdf_1_4_0_beta_1: buildEntry({ ...common, product: 'PinchPDF', channel: 'beta', version: '1.4.0-beta.1', fileName: 'PinchPDF-1.4.0-beta.1-x64.exe', bytes: installer('PinchPDF 1.4.0-beta.1'), notes: ['Try the new batch mode'] }),
  nodupe_2_0_0: buildEntry({ ...common, product: 'NoDupe', channel: 'stable', version: '2.0.0', fileName: 'NoDupe-2.0.0-x64.exe', bytes: installer('NoDupe 2.0.0'), notes: ['Rebuilt scanner'] }),
};

let pinchpdf = null;
for (const key of ['pinchpdf_1_2_0', 'pinchpdf_1_3_0', 'pinchpdf_1_4_0_beta_1']) pinchpdf = mergeIndex(pinchpdf, 'PinchPDF', entries[key]);
const nodupe = mergeIndex(null, 'NoDupe', entries.nodupe_2_0_0);

const vectors = {
  note: 'TEST-ONLY key. Generated by scripts/generate-release-vectors.mjs; do not edit by hand.',
  signing_seed_test_only: seed,
  public_key: publicKeyFromSeed(seed),
  message_format: 'pinchpdf-release-v1|<Product>|<channel>|<version>|<sha256>|<size>',
  messages: Object.fromEntries(Object.entries(entries).map(([name, entry]) => [name, releaseMessage(name.startsWith('nodupe') ? 'NoDupe' : 'PinchPDF', entry)])),
  entries,
  indexes: { PinchPDF: pinchpdf, NoDupe: nodupe },
};

writeFileSync(new URL('../test/release-vectors.json', import.meta.url), `${JSON.stringify(vectors, null, 2)}\n`);
console.log('wrote test/release-vectors.json');
